"""Convert SentinelKilnDB parquet files into an Ultralytics YOLO-OBB dataset.

Input : data/skdb/{train,val,test}/{split}.parquet
Output: data/yolo/images/{split}/<name>.png
        data/yolo/labels/{split}/<name>.txt     (empty file = no kiln, kept as a negative)
        data/yolo/kilns.yaml                    (absolute path, used for training)
        data/yolo/stats.json                    (counts and checks)

Checks done while converting:
- every YOLO-OBB label line parses, class id in the frozen map, corners in [0, 1] (clipped if not)
- the class map agrees with the DOTA label text (class name + corners within 1 px)
- image names are unique within a split, and no image appears in two splits

Run from repo root:
    python ml/prepare_dataset.py                 # full conversion (resumes, skips existing files)
    python ml/prepare_dataset.py --limit 500     # quick trial on 500 images per split
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from collections import Counter
from pathlib import Path

import pyarrow.parquet as pq

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from ml.labels import CLASS_NAMES, clip_box, format_obb_line, matches_dota, parse_obb_line  # noqa: E402

SRC = ROOT / "data" / "skdb"
DST = ROOT / "data" / "yolo"
SPLITS = ["train", "val", "test"]
PNG_MAGIC = b"\x89PNG\r\n\x1a\n"


def convert_split(split: str, limit: int | None, overwrite: bool, seen_all: dict[str, str]) -> dict:
    img_dir = DST / "images" / split
    lbl_dir = DST / "labels" / split
    img_dir.mkdir(parents=True, exist_ok=True)
    lbl_dir.mkdir(parents=True, exist_ok=True)

    s = Counter()
    boxes = Counter()
    problems: list[str] = []
    seen: set[str] = set()
    pf = pq.ParquetFile(SRC / split / f"{split}.parquet")
    t0 = time.time()

    for batch in pf.iter_batches(batch_size=2000, columns=["image_name", "image", "yolo_obb_label", "dota_label"]):
        for name, img, obb, dota in zip(*(batch.column(c).to_pylist() for c in
                                          ["image_name", "image", "yolo_obb_label", "dota_label"])):
            if limit is not None and s["images"] >= limit:
                break
            stem = Path(name).stem
            if stem in seen:
                s["duplicate_names"] += 1
                continue
            seen.add(stem)
            if stem in seen_all:
                s["cross_split_duplicates"] += 1
                if len(problems) < 20:
                    problems.append(f"{stem} also in {seen_all[stem]}")
            seen_all.setdefault(stem, split)

            img_path = img_dir / f"{stem}.png"
            if overwrite or not img_path.exists():
                if not img.startswith(PNG_MAGIC):
                    raise SystemExit(f"{split}/{name}: image bytes are not PNG")
                img_path.write_bytes(img)
                s["images_written"] += 1
            s["images"] += 1

            lines = []
            for i, line in enumerate(obb or []):
                try:
                    box = parse_obb_line(line)
                except ValueError as e:
                    s["bad_label_lines"] += 1
                    if len(problems) < 20:
                        problems.append(f"{split}/{stem}: {e}")
                    continue
                if dota and i < len(dota) and not matches_dota(box, dota[i]):
                    s["dota_mismatch"] += 1
                    if len(problems) < 20:
                        problems.append(f"{split}/{stem}: OBB/DOTA disagree: {line!r} vs {dota[i]!r}")
                box, clipped = clip_box(box)
                s["clipped_boxes"] += clipped
                boxes[CLASS_NAMES[box.cls]] += 1
                lines.append(format_obb_line(box))

            lbl_path = lbl_dir / f"{stem}.txt"
            if overwrite or not lbl_path.exists():
                lbl_path.write_text("\n".join(lines) + ("\n" if lines else ""), encoding="ascii")
            s["with_kilns" if lines else "negatives"] += 1

        if limit is not None and s["images"] >= limit:
            break
        print(f"  {split}: {s['images']:>6} images  ({time.time() - t0:.0f}s)", end="\r", flush=True)

    print(f"  {split}: {s['images']:>6} images  ({time.time() - t0:.0f}s)")
    return {"counts": dict(s), "boxes": dict(boxes), "problems": problems}


def write_yaml() -> Path:
    y = DST / "kilns.yaml"
    names = "\n".join(f"  {k}: {v}" for k, v in CLASS_NAMES.items())
    y.write_text(
        "# Generated by ml/prepare_dataset.py - absolute path for this machine. Template: ml/kilns.yaml\n"
        f"path: {DST.as_posix()}\ntrain: images/train\nval: images/val\ntest: images/test\nnames:\n{names}\n",
        encoding="utf-8")
    return y


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=None, help="max images per split (trial run)")
    ap.add_argument("--overwrite", action="store_true", help="rewrite files that already exist")
    ap.add_argument("--splits", nargs="+", default=SPLITS, choices=SPLITS)
    args = ap.parse_args()

    seen_all: dict[str, str] = {}
    report = {}
    for split in args.splits:
        report[split] = convert_split(split, args.limit, args.overwrite, seen_all)
    yaml_path = write_yaml()
    (DST / "stats.json").write_text(json.dumps(report, indent=2), encoding="utf-8")

    print("\nsplit   images  with_kilns  negatives   CFCBK    FCBK  Zigzag  clipped  bad  dota_mismatch  x-split_dup")
    for split, r in report.items():
        c, b = r["counts"], r["boxes"]
        print(f"{split:<6} {c.get('images', 0):>7} {c.get('with_kilns', 0):>11} {c.get('negatives', 0):>10} "
              f"{b.get('CFCBK', 0):>7} {b.get('FCBK', 0):>7} {b.get('Zigzag', 0):>7} {c.get('clipped_boxes', 0):>8} "
              f"{c.get('bad_label_lines', 0):>4} {c.get('dota_mismatch', 0):>14} {c.get('cross_split_duplicates', 0):>12}")
    for split, r in report.items():
        for p in r["problems"][:5]:
            print("  !", p)
    print(f"\ndataset yaml: {yaml_path}\nstats: {DST / 'stats.json'}")


if __name__ == "__main__":
    main()
